// Emits the design tokens for non-CSS consumers (React Native, native apps, design tools):
// dist/tokens/tokens.json, index.mjs, index.cjs and index.d.ts (the `@dskripchenko/ui/tokens`
// entry). The CSS files stay the single source: primitives from src/tokens/*.css, semantic
// tokens from the light and dark blocks of src/styles/themes.css plus its theme-independent
// alias block, resolved per theme. `var()` references are resolved; px, ms and unitless numbers
// become numbers, everything else (colors, shadows, font stacks, easings) stays a string.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const PREFIX = '--uid-'
const TOKEN_FILES = ['colors', 'typography', 'spacing', 'sizing', 'radius', 'motion', 'z-index', 'breakpoints']

/** Declarations of each top-level block, keyed by its selector. Comments are dropped. */
export function parseBlocks(css) {
  const text = css.replace(/\/\*[\s\S]*?\*\//g, '')
  const blocks = []
  const re = /([^{}]+)\{([^{}]*)\}/g
  let m
  while ((m = re.exec(text))) {
    const selector = m[1].trim().replace(/\s+/g, ' ')
    const decls = {}
    for (const part of m[2].split(';')) {
      const i = part.indexOf(':')
      if (i < 0) continue
      const name = part.slice(0, i).trim()
      if (!name.startsWith(PREFIX)) continue
      decls[name.slice(PREFIX.length)] = part.slice(i + 1).trim().replace(/\s+/g, ' ')
    }
    blocks.push({ selector, decls })
  }
  return blocks
}

/** Resolves every `var(--uid-x[, fallback])` against `scope`; throws on an unknown or cyclic token. */
export function resolveAll(scope) {
  const out = {}
  const visiting = new Set()
  const resolveOne = (key) => {
    if (key in out) return out[key]
    if (!(key in scope)) throw new Error(`Unknown token --uid-${key}`)
    if (visiting.has(key)) throw new Error(`Cyclic token --uid-${key}`)
    visiting.add(key)
    let value = scope[key]
    // Innermost var() first, so a var() inside a fallback is handled too.
    for (let guard = 0; value.includes('var('); guard++) {
      if (guard > 50) throw new Error(`Cannot resolve --uid-${key}: ${scope[key]}`)
      value = value.replace(/var\(\s*--uid-([a-z0-9-]+)\s*(?:,\s*([^()]*))?\)/g, (_, ref, fallback) =>
        ref in scope ? resolveOne(ref) : fallback !== undefined ? fallback.trim() : resolveOne(ref),
      )
    }
    visiting.delete(key)
    out[key] = value
    return value
  }
  for (const key of Object.keys(scope)) resolveOne(key)
  return out
}

/** `16px` → 16, `100ms` → 100, `1.25` → 1.25, `0` → 0; anything else is kept as a string. */
export function toValue(raw) {
  const m = /^(-?\d+(?:\.\d+)?)(px|ms)?$/.exec(raw)
  return m ? Number(m[1]) : raw
}

const mapValues = (obj, fn) => Object.fromEntries(Object.entries(obj).map(([k, v]) => [k, fn(v)]))

export function extractTokens(root) {
  const read = (rel) => readFileSync(resolve(root, rel), 'utf8')
  const primitiveDecls = {}
  for (const f of TOKEN_FILES) {
    for (const b of parseBlocks(read(`src/tokens/${f}.css`))) Object.assign(primitiveDecls, b.decls)
  }

  const themeBlocks = parseBlocks(read('src/styles/themes.css'))
  const pick = (selector) => {
    const block = themeBlocks.find((b) => b.selector === selector)
    if (!block) throw new Error(`themes.css: no block ${selector}`)
    return block.decls
  }
  const light = pick(":root[data-theme='light']")
  const dark = pick(":root[data-theme='dark']")
  const aliases = pick(':root')

  const primitives = mapValues(resolveAll(primitiveDecls), toValue)
  const theme = (decls) => {
    const resolved = resolveAll({ ...primitiveDecls, ...decls, ...aliases })
    const keys = [...Object.keys(decls), ...Object.keys(aliases)]
    return Object.fromEntries(keys.map((k) => [k, toValue(resolved[k])]))
  }
  return { primitives, themes: { light: theme(light), dark: theme(dark) } }
}

function emit(root, tokens) {
  const dir = resolve(root, 'dist/tokens')
  mkdirSync(dir, { recursive: true })
  const banner = '// @dskripchenko/ui — design tokens. Auto-generated by scripts/build-tokens.mjs. Do not edit.\n'
  const json = JSON.stringify(tokens, null, 2)
  writeFileSync(resolve(dir, 'tokens.json'), json + '\n')
  writeFileSync(resolve(dir, 'index.mjs'), `${banner}export const primitives = ${JSON.stringify(tokens.primitives, null, 2)}\n\nexport const themes = ${JSON.stringify(tokens.themes, null, 2)}\n`)
  writeFileSync(resolve(dir, 'index.cjs'), `${banner}'use strict'\nexports.primitives = ${JSON.stringify(tokens.primitives, null, 2)}\n\nexports.themes = ${JSON.stringify(tokens.themes, null, 2)}\n`)
  const keys = (obj) => Object.keys(obj).map((k) => `  | '${k}'`).join('\n')
  writeFileSync(
    resolve(dir, 'index.d.ts'),
    `${banner}/** Theme-independent tokens (palette, type scale, spacing, radius, motion, z-index, breakpoints), without the --uid- prefix. */\nexport type PrimitiveToken =\n${keys(tokens.primitives)}\n\n/** Tokens that change with the theme (surfaces, text, borders, accent, statuses, shadows) and the --uid-color-* aliases. */\nexport type ThemeToken =\n${keys(tokens.themes.light)}\n\nexport type ThemeName = 'light' | 'dark'\n\n/** px and ms values and unitless numbers are numbers; colors, shadows, font stacks and easings are strings. */\nexport type TokenValue = string | number\n\nexport declare const primitives: Readonly<Record<PrimitiveToken, TokenValue>>\nexport declare const themes: Readonly<Record<ThemeName, Readonly<Record<ThemeToken, TokenValue>>>>\n`,
  )
  process.stdout.write(`build-tokens: ${Object.keys(tokens.primitives).length} primitives, ${Object.keys(tokens.themes.light).length} theme tokens\n`)
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
  emit(root, extractTokens(root))
}
